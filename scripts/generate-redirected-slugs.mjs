// Generates lib/redirected-slugs.ts from the redirect table in next.config.js.
//
// Why this exists: lib/guides.ts holds 12 hardcoded guides, and 10 of them are
// also configured as redirects. getRelatedGuidesForJob() read the raw array, so
// job detail pages rendered internal links to URLs that immediately redirect
// away. /sarkari-naukri/ssc-cgl-2026 and /sarkari-naukri/ssc-chsl-2026 each
// carried three.
//
// A redirected internal link costs twice: Google spends a fetch to be told to
// go elsewhere, and the link equity passes through a hop instead of landing.
// GSC reported exactly 3 URLs under "Page with redirect".
//
// Generating the list rather than hand-maintaining it means a redirect added
// later cannot silently re-open the hole. Re-run after editing redirects:
//     node scripts/generate-redirected-slugs.mjs

import { readFileSync, writeFileSync } from "node:fs";

const config = readFileSync("next.config.js", "utf8");
const slugs = [...config.matchAll(/source:\s*'\/blog\/([a-z0-9-]+)'/g)]
  .map((m) => m[1])
  .sort();

const unique = [...new Set(slugs)];

const out = `// GENERATED by scripts/generate-redirected-slugs.mjs. Do not edit by hand.
//
// Blog slugs that next.config.js redirects away. Nothing on the site should
// link to these: the link would cost a redirect hop for both crawlers and
// readers. Re-run the generator after changing the redirect table.

export const REDIRECTED_BLOG_SLUGS: ReadonlySet<string> = new Set([
${unique.map((s) => `  "${s}",`).join("\n")}
]);

export function isRedirectedBlogSlug(slug: string): boolean {
  return REDIRECTED_BLOG_SLUGS.has(slug);
}
`;
writeFileSync("lib/redirected-slugs.ts", out);
console.log(`wrote lib/redirected-slugs.ts with ${unique.length} redirected blog slugs`);
